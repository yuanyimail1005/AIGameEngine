#pragma once

#include "JsonUtils.h"

#include <filesystem>
#include <functional>
#include <map>
#include <string>
#include <vector>

namespace Ember {

	class EditorContext;

	struct CommandInfo
	{
		std::string Name;
		std::string Category;
		std::string Description;
		Json Params; // { "param": "type - description" } documentation for agents
		std::function<Json(const Json&)> Handler;
	};

	// The editor's command API: every operation an AI agent (or script / test) can perform, as JSON in, JSON out.
	// Requests: {"id": any, "method": "create_entity", "params": {...}}
	// Responses: {"id": any, "result": ...} or {"id": any, "error": {"message": "..."}}
	// The full reference is generated by the `list_commands` command and documented in docs/AIControl.md.
	class EditorCommands
	{
	public:
		explicit EditorCommands(EditorContext& context);

		// Runs a command; throws CommandError on failure.
		Json Execute(const std::string& method, const Json& params);
		// Runs a full request object and returns the response object (never throws).
		Json HandleRequest(const Json& request);
		// Parses one line of JSON and handles it (protocol entry point for servers and batch files).
		std::string HandleLine(const std::string& line);

		const std::map<std::string, CommandInfo>& GetCommands() const { return m_Commands; }

		// Set by the application.
		std::function<void()> OnQuit;
		std::filesystem::path RuntimeExecutable; // used by export_game

	private:
		void Register(const std::string& name, const std::string& category, const std::string& description, Json params,
			std::function<Json(const Json&)> handler);
		void RegisterGeneral();
		void RegisterProjectAndScene();
		void RegisterEntities();
		void RegisterAssets();
		void RegisterPlayAndRender();

	private:
		EditorContext& m_Context;
		std::map<std::string, CommandInfo> m_Commands;
	};

}
